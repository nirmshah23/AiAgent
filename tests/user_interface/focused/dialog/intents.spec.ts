import { test, expect } from '../../../../apps/frontend/node_modules/@playwright/test';

test('creates, validates, edits and deletes an intent through the policy API', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Intent settings', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Intent settings', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Delete intent', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Add intent', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('TEST_LOOKUP');
  await page.getByLabel('Type', { exact: true }).click();
  await page.getByRole('option', { name: 'Business', exact: true }).click();
  await page.getByLabel('Description', { exact: true }).fill('Look up an example');
  await page.getByRole('button', { name: 'Fields', exact: true }).click();
  await page.getByRole('button', { name: 'Add Fields', exact: true }).click();
  await page.getByRole('group', { name: 'Fields 1', exact: true }).getByLabel('Name', { exact: true }).fill('claimId');
  await page.getByRole('button', { name: 'Rules', exact: true }).click();
  await page.getByRole('button', { name: 'Add Rules', exact: true }).click();
  await page.getByRole('button', { name: 'Add Conditions', exact: true }).click();
  await page.getByRole('group', { name: 'Conditions 1', exact: true }).getByRole('textbox', { name: 'Field', exact: true }).fill('claimId');
  await page.getByRole('button', { name: 'API bindings', exact: true }).click();
  await page.getByRole('button', { name: 'Configure API bindings', exact: true }).click();
  const api = page.getByRole('group', { name: 'API bindings', exact: true });
  await api.getByLabel('Endpoint', { exact: true }).fill('claims');
  const query = api.getByRole('group', { name: 'Optional query', exact: true });
  await query.getByLabel('New Optional query key', { exact: true }).fill('id');
  await query.getByRole('button', { name: 'Add binding', exact: true }).click();
  await query.getByLabel('id binding', { exact: true }).fill('claimId');
  await page.getByRole('button', { name: 'Responses', exact: true }).click();
  await page.getByRole('button', { name: 'Add Responses', exact: true }).click();
  await page.getByLabel('Responses 1', { exact: true }).fill('Example response.');
  await page.getByRole('button', { name: 'Next intent', exact: true }).click();
  await page.getByRole('button', { name: 'Configure Next intent', exact: true }).click();
  await page.getByRole('textbox', { name: 'Next intent', exact: true }).fill('UNKNOWN');
  await page.getByRole('button', { name: 'Save configuration', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Unknown next_intent');
  await page.getByRole('textbox', { name: 'Next intent', exact: true }).fill('END');
  await page.getByRole('button', { name: 'Save configuration', exact: true }).click();
  await expect(page.getByText('Configuration saved. New calls will use these settings.')).toBeVisible();
  await page.getByRole('button', { name: 'Reload configuration', exact: true }).click();
  await page.getByRole('button', { name: 'TEST_LOOKUP', exact: true }).click();
  await expect(page.getByLabel('Description', { exact: true })).toHaveValue('Look up an example');
  const stored = await (await page.request.get('/api/v1/dialog-policy')).json();
  const intent = stored.configuration.intents.find((item: { name: string }) => item.name === 'TEST_LOOKUP');
  expect(intent.rules).toEqual([{ conditions: [{ field: 'claimId', operator: 'present', value: null }] }]);
  expect(intent.api.optional_query).toEqual({ id: 'claimId' });
  await page.getByLabel('Description', { exact: true }).fill('Updated example');
  await page.getByRole('button', { name: 'Save configuration', exact: true }).click();
  await expect(page.getByText('All changes saved', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/dialog/mobile-nested.png', fullPage: true, animations: 'disabled' });
  // Keep screenshots focused on the primary editor and one nested section.
  await page.getByRole('button', { name: 'Rules', exact: true }).click();
  await page.getByRole('button', { name: 'API bindings', exact: true }).click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/dialog/desktop.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/dialog/mobile.png', fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Delete intent', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'TEST_LOOKUP', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Delete intent', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Delete intent', exact: true }).click();
  await page.getByRole('button', { name: 'Save configuration', exact: true }).click();
  await expect(page.getByRole('button', { name: 'TEST_LOOKUP', exact: true })).toHaveCount(0);
  await expect(page.getByText('All changes saved', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('recovers from load failure and confirms discarding unsaved edits', async ({ page }) => {
  await page.route('**/api/v1/dialog-policy', route => route.fulfill({ status: 503, json: { detail: 'Unavailable' } }), { times: 1 });
  await page.goto('/');
  await page.getByRole('button', { name: 'Intent settings', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Could not load');
  await page.getByRole('button', { name: 'Retry loading', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Add intent', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Add intent', exact: true }).click();
  await page.getByRole('textbox', { name: 'Name', exact: true }).fill('UNSAVED');
  await page.getByRole('button', { name: 'Back to voice', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue('UNSAVED');
  await page.getByRole('button', { name: 'Back to voice', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Discard changes', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Start session', exact: true })).toBeVisible();
});
